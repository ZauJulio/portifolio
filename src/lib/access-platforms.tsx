function normalize(platform: string): string {
  return platform
    .toLowerCase()
    .trim()
    .replace(/[\s_+]+/g, "-")
    .replace(/^hbo$/, "hbo-max")
    .replace(/^prime$/, "prime-video")
    .replace(/^disney$/, "disney-plus")
    .replace(/^paramount$/, "paramount-plus")
    .replace(/^apple$/, "apple-tv")
    .replace(/^ps2$|^playstation-?2$/, "ps2")
    .replace(/^ps[1345n]?$|^playstation.*/, "playstation");
}

/** Resolve a platform key to its label, brand color and icon, with a generic fallback. */
export function resolvePlatform(platform: string): PlatformEntry {
  const entry = REGISTRY[normalize(platform)];
  if (entry) return entry;

  return { label: platform, color: "#9CA3AF", icon: <LinkIcon className="size-4" /> };
}
